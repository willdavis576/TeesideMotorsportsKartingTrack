"""Place things on the Teesside layout in rFactor 2's coordinate system.

Coordinates: the GMT bounding boxes show rF2 = (x, y, -z) of our OBJ/centreline, i.e. east, up,
north. Headings: the sample track's grid shows a car with yaw angle a faces (-sin a, 0, -cos a).
Both were checked against the sample track (Joesville) and the first Teesside export.
"""
import csv
import math
import re

import numpy as np

MARKER = "// generated by tools/make_track_folder.py"


def load_centreline(path):
    """(N, 3) rF2 positions along the lap, metres, plus the distance of each sample."""
    rows = list(csv.DictReader(open(path)))
    xyz = np.array([[float(r["x"]), float(r["y_up"]), -float(r["z"])] for r in rows])
    dist = np.array([float(r["dist_m"]) for r in rows])
    return xyz, dist


class Lap:
    def __init__(self, centreline_csv):
        self.xyz, self.dist = load_centreline(centreline_csv)
        self.step = self.dist[1] - self.dist[0]
        self.n = len(self.xyz)
        self.length = self.n * self.step

    def index(self, d):
        return int(round(d / self.step)) % self.n

    def forward(self, i):
        f = self.xyz[(i + 2) % self.n] - self.xyz[(i - 2) % self.n]
        f[1] = 0
        return f / np.linalg.norm(f)

    def yaw(self, i):
        f = self.forward(i)
        return math.atan2(-f[0], -f[2])

    def side(self, i):
        """Unit vector across the track (horizontal, perpendicular to travel)."""
        f = self.forward(i)
        return np.array([f[2], 0.0, -f[0]])

    def at(self, d, lateral=0.0, up=0.0):
        """Position `d` metres along the lap, `lateral` metres to one side, and its yaw."""
        i = self.index(d)
        p = self.xyz[i] + self.side(i) * lateral + np.array([0, up, 0])
        return p, self.yaw(i)


def fmt3(v):
    return f"({v[0]:.3f},{v[1]:.3f},{v[2]:.3f})"


def ori(yaw):
    return f"(0.000,{yaw:.3f},0.000)"


def section_counts(template):
    """How many entries each spawn section of an AIW has, e.g. {"[GRID]": 75, "[PITS]": 15, ...}."""
    keys = {"[GRID]": "GridIndex", "[ALTGRID]": "GridIndex", "[TELEPORT]": "GridIndex",
            "[PITS]": "TeamIndex", "[AUX]": "LocationIndex"}
    parts = re.split(r"^(\[\w+\])[ \t]*\r?$", template.replace("\r\n", "\n"), flags=re.M)
    counts = {}
    for name, body in zip(parts[1::2], parts[2::2]):
        if name in keys:
            counts[name] = len(re.findall(rf"^{keys[name]}=", body, flags=re.M))
        if name == "[PITS]":
            teams = max(counts[name], 1)
            counts["garages"] = len(re.findall(r"^GarPos=", body, flags=re.M)) // teams
    return counts


def relocate_aiw(template, lap):
    """The sample AIW with its grid, teleport, pit, garage and aux spots moved onto this layout's start
    straight. The waypoints (racing line) are left as the sample's: they still need recording for this
    track, but the file stays valid and the car spawns on the right track, facing the right way.
    Every section keeps exactly the sample's number of entries: pit teams are tied to pit-lane branches
    in the waypoints, and a different count crashed rF2 while loading."""
    counts = section_counts(template)
    teams, garages = counts.get("[PITS]", 0), counts.get("garages", 0)

    def grid_block(offset, grid):
        out = []
        for k in range(grid):
            p, a = lap.at(-(offset + 7.0 * (k // 2)), lateral=2.0 if k % 2 == 0 else -2.0)
            out += [f"GridIndex={k}", f"Pos={fmt3(p)}", f"Ori={ori(a)}"]
        return out

    pits = []
    for t in range(teams):
        d = 15.0 + 8.0 * t  # along the straight after the line; team 0 (the player) first
        p, a = lap.at(d)
        pits += [f"TeamIndex={t}", f"PitPos={fmt3(p)}", f"PitOri={ori(a)}"]
        for g in range(garages):
            gp, ga = lap.at(d, lateral=(g - (garages - 1) / 2) * 3.0)
            pits += [f"GarPos=({g},{gp[0]:.3f},{gp[1]:.3f},{gp[2]:.3f})", f"GarOri=({g},0.000,{ga:.3f},0.000)"]

    aux = []
    for k in range(counts.get("[AUX]", 0)):
        p, a = lap.at(-30.0)
        aux += [f"LocationIndex={k}", f"Pos={fmt3(p)}", f"Ori={ori(a)}"]

    new = {"[GRID]": grid_block(8.0, counts.get("[GRID]", 0)),
           "[ALTGRID]": grid_block(8.0, counts.get("[ALTGRID]", 0)),
           "[TELEPORT]": grid_block(8.0, counts.get("[TELEPORT]", 0)),
           "[PITS]": pits, "[AUX]": aux}
    parts = re.split(r"^(\[\w+\])[ \t]*\r?$", template.replace("\r\n", "\n"), flags=re.M)
    out = [parts[0].rstrip("\n").split("\n")[0], MARKER + ": sample racing line, Teesside grid/pits/garages",
           *parts[0].rstrip("\n").split("\n")[1:]]
    for name, body in zip(parts[1::2], parts[2::2]):
        out.append(name)
        if name in new:
            out += new[name] + [""]
        else:
            out += body.strip("\n").split("\n") + ([""] if name != "[Waypoint]" else [])
    return "\n".join(out) + "\n"


def make_cam(template, lap, count=12, distance=18.0, height=5.0, clearance_xy=None):
    """Tracking TV cameras spaced around the lap, each beside the track on whichever side has more
    room, using the first TrackingCam block of the sample .cam as the template. No ambient sounds."""
    m = re.search(r"TrackingCam=\S+\s*\{.*?\n\}", template.replace("\r\n", "\n"), flags=re.S)
    if not m:
        raise ValueError("no TrackingCam block in the sample .cam")
    block = m.group(0)
    flat = lap.xyz[:, [0, 2]]
    spacing = lap.length / count
    out = [MARKER + ": Teesside tracking cameras"]
    for k in range(count):
        d = (k + 0.5) * spacing
        i = lap.index(d)
        best = None
        for s in (1, -1):
            p = lap.xyz[i] + lap.side(i) * s * distance
            # Room on this side: distance to any part of the track other than this stretch.
            gap = np.abs((np.arange(lap.n) - i + lap.n // 2) % lap.n - lap.n // 2) * lap.step
            others = flat[gap > min(40.0, lap.length / 4)]
            room = np.linalg.norm(others - p[[0, 2]], axis=1).min() if len(others) else np.inf
            if best is None or room > best[0]:
                best = (room, p)
        cam = best[1] + np.array([0, height, 0])
        target = lap.xyz[i]
        look = target - cam
        yaw = math.atan2(-look[0], -look[2])
        b = re.sub(r"TrackingCam=\S+", f"TrackingCam=TRACKING{k + 1:03d}", block, count=1)
        b = re.sub(r"Position=\([^)]*\)", f"Position=({cam[0]:.6f}, {cam[1]:.6f}, {cam[2]:.6f})", b)
        b = re.sub(r"Orientation=\([^)]*\)", f"Orientation=(0.000000, {yaw:.6f}, 0.000000)", b)
        b = re.sub(r"ActivationLocation=\([^)]*\)",
                   f"ActivationLocation=({target[0]:.6f}, {target[1]:.6f}, {target[2]:.6f})", b)
        b = re.sub(r"ActivationRadius=\([^)]*\)", f"ActivationRadius=({spacing * 0.6:.6f})", b)
        out.append(b)
    first_line = template.replace("\r\n", "\n").split("\n")[0]
    return (first_line + "\n" if first_line.startswith("//") else "") + "\n".join(out) + "\n"


def reflection_mappers(instances, lap):
    """The two reflection maps rF2 asks for ("Static01 and Refmap0 at least"), laid out like the
    sample track's: a static cube map in the middle of the track and one that follows the car."""
    drivable = [n for n in instances if re.match(r"(road|kerb|verge|runoff|terrain)", n)]
    visible = [n for n in instances if not re.match(r"(x|tyrewall_collision)", n)]
    centre = lap.xyz.mean(axis=0)
    lines = ["", "//-------------------------------------------------------",
             "//-------------------REFLECTION MAPS---------------------",
             "//-------------------------------------------------------", "",
             "ReflectionMapper=STATIC01", "{", "  Type=Cubic", "  TextureSize=(512)", "  UpdateRate=(0.100)",
             "  StaticSwitch=(100.000)", f"  Pos=({centre[0]:.6f},0.000000,{centre[2]:.6f})"]
    lines += [f"  IncludeIns={n}" for n in drivable] + ["}", ""]
    lines += ["ReflectionMapper=REFMAP0", "{", "  Type=Cubic", "  TextureSize=(1024)", "  UpdateRate=(100.000)",
              "  StaticSwitch=(100.000)", "  TrackingIns=True"]
    lines += [f"  IncludeIns={n}" for n in visible] + ["}", ""]
    return "\n".join(lines)
