def track_map(xy, size, fg, bg, line_frac=0.012, title=None):
    """Plan view of the centreline as an RGBA image: fg line on bg (bg alpha 0 = transparent)."""
    import numpy as np
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from PIL import Image

    w, h = size
    fig = plt.figure(figsize=(w / 100, h / 100), dpi=100)
    fig.patch.set_alpha(0)
    ax = fig.add_axes([0.08, 0.08, 0.84, 0.84] if not title else [0.04, 0.1, 0.56, 0.8])
    ax.set_axis_off()
    pts = np.vstack([xy, xy[:1]])
    ax.plot(pts[:, 0], pts[:, 1], color=fg, lw=max(1.5, min(w, h) * line_frac), solid_capstyle="round",
            solid_joinstyle="round")
    ax.plot(*xy[0], "o", color="white", ms=max(2, min(w, h) * 0.03), mec="black")  # start/finish
    ax.set_aspect("equal")
    if title:
        fig.text(0.64, 0.56, title, color="white", fontsize=h / 30, fontweight="bold", va="center")
        fig.text(0.64, 0.48, "Middlesbrough, UK", color="#cccccc", fontsize=h / 50, va="center")
    fig.canvas.draw()
    fg_img = Image.frombuffer("RGBA", fig.canvas.get_width_height(), fig.canvas.buffer_rgba()).copy()
    plt.close(fig)
    out = Image.new("RGBA", fg_img.size, bg)
    out.alpha_composite(fg_img)
    return out.resize(size)


def write_icons(centreline_csv, layout_dir, root, folder, layout, track_name):
    """Track-map images in the places and sizes the sample track has them."""
    import csv
    import numpy as np

    rows = list(csv.DictReader(open(centreline_csv)))
    xy = np.array([[float(r["x"]), -float(r["z"])] for r in rows])  # east, north
    made = []

    def dds(img, path):
        write_dds(np.asarray(img.convert("RGBA")), path)
        made.append(path)

    def save(img, path, fmt):
        img.save(path, fmt)
        made.append(path)

    dds(track_map(xy, (512, 512), "white", (40, 40, 40, 255)), root / f"{folder}Icon.dds")
    save(track_map(xy, (102, 87), "white", (200, 20, 20, 255), 0.025), layout_dir / f"{layout}icon.tga", "TGA")
    dds(track_map(xy, (512, 512), "#f0d000", (40, 40, 40, 255)), layout_dir / f"{layout}SMicon.dds")
    save(track_map(xy, (190, 128), "#f0d000", (0, 0, 0, 0), 0.02), layout_dir / f"{layout}Thmb.tga", "TGA")
    save(track_map(xy, (1920, 1080), "#e05030", (25, 25, 30, 255), 0.006, title=track_name).convert("RGB"),
         layout_dir / f"{layout}_loading.jpg", "JPEG")
    return made


def placeholder_copies(ref, layout_dir, layout):
    """Copy the sample layout's weather file (.wet), renamed for this layout and with its RealRoad
    presets switched to "natural", unless the layout has its own (edited) one.

    RealRoad presets (.rrbin) are NOT copied: they store rubber/dust per vertex of the sample track's
    road and rF2 rejects them on any other track. Copies made by earlier versions of this script
    (byte-identical to the sample's) are removed; presets saved for this track are kept.
    Returns (copied, removed)."""
    sample_gdb = next((p for p in ref.rglob("*") if p.suffix.lower() == ".gdb"), None)
    if sample_gdb is None:
        return [], []
    made, removed = [], []
    for src in sample_gdb.parent.iterdir():
        ext = src.suffix.lower()
        if ext == ".wet":
            existing = [p for p in layout_dir.iterdir() if p.suffix.lower() == ".wet"]
            # Replace our own earlier copies (generated marker, or identical to the sample); keep yours.
            if existing and not (MARKER.encode() in existing[0].read_bytes()
                                 or existing[0].read_bytes() == src.read_bytes()):
                continue
            for p in existing:
                p.unlink()
            text = src.read_bytes().decode("latin-1").replace("\r\n", "\n")
            # The sample starts some sessions from its own RealRoad presets ("preset:X.rrbin"), which
            # don't exist (or fit) here; "natural" lets rubber build up on this track instead.
            text = re.sub(r'"preset:[^"]*"', '"natural"', text)
            lines = text.split("\n")
            lines.insert(1 if lines and lines[0].startswith("//") else 0,
                         MARKER + ": the sample track's weather, RealRoad presets set to natural")
            dst = layout_dir / f"{layout}{src.suffix}"
            write_crlf(dst, "\n".join(lines))
            made.append(dst)
        elif ext == ".rrbin":
            stale = layout_dir / src.name
            if stale.exists() and stale.read_bytes() == src.read_bytes():
                stale.unlink()
                removed.append(stale)
    return made, removed


def control_clone(ref, out, name="ZZTestA"):
    """An exact copy of the sample track under a new name, as a control: if even this doesn't show in
    Dev Mode's track list, the problem isn't in our files."""
    dst = out / name
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(ref, dst)
    gdb = next(p for p in dst.rglob("*") if p.suffix.lower() == ".gdb")
    old_layout = gdb.stem
    new_layout = f"{name}_Layout"
    layout_dir = gdb.parent.rename(gdb.parent.with_name(new_layout))
    for f in list(layout_dir.iterdir()):
        if f.stem.lower().startswith(old_layout.lower()):
            f.rename(f.with_name(new_layout + f.name[len(old_layout):]))
    gdb = layout_dir / f"{new_layout}{gdb.suffix}"
    text = gdb.read_bytes().decode("latin-1")
    text = re.sub(rf"^{re.escape(old_layout)}", new_layout, text, count=1, flags=re.I)
    text = re.sub(r"(TrackName\s*=).*", r"\1 ZZ Test A (sample copy)", text)
    text = re.sub(r"(VenueName\s*=).*", r"\1 ZZ Test A", text)
    gdb.write_bytes(text.encode("latin-1"))
    return dst


def write_crlf(path, text):
    """Write with Windows line endings, byte for byte. (write_text would translate "\n" again on
    Windows, turning "\r\n" into "\r\r\n", which rF2 can't parse.)"""
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    Path(path).write_bytes("\r\n".join(lines).encode("ascii", errors="replace"))


def instance_blocks(scn_text):
    """Every `Instance=... { ... }` block from an exported .scn, as text (braces balanced)."""
    blocks, pos = [], 0
    for m in re.finditer(r"Instance\s*=\s*[^\s{]+\s*\{", scn_text):
        if m.start() < pos:
            continue
        depth, i = 1, m.end()
        while depth and i < len(scn_text):
            depth += {"{": 1, "}": -1}.get(scn_text[i], 0)
            i += 1
        blocks.append(scn_text[m.start():i])
        pos = i
    return blocks


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gmt", default="GMT", help="folder with the 3DSimED export (.gmt files and the .scn)")
    ap.add_argument("--scn", help="the exported .scn (default: the only .scn in --gmt)")
    ap.add_argument("--textures", default="build/textures")
    ap.add_argument("--summary", default="build/summary.json")
    ap.add_argument("--reference", default="reference/Joesville", help="ModDev sample track folder")
    ap.add_argument("--out", default="dist/Locations", help="Locations folder to write into")
    ap.add_argument("--folder", default="TeessideKarting")
    ap.add_argument("--layout", default="Teesside_Karting")
    ap.add_argument("--track-name", default="Teesside Karting")
    ap.add_argument("--venue", default="Teesside Motorsports")
    ap.add_argument("--centreline", default="build/centreline.csv", help="for the track-map icons")
    ap.add_argument("--filter", nargs="*", default=[],
                    help="extra vehicle classes allowed on the track (from the car's .veh 'Classes=' line), "
                         "added to the sample track's list, e.g. --filter Kart")
    ap.add_argument("--control-clone", action="store_true",
                    help="also write ZZTestA, an exact renamed copy of the sample track, as a test")
    ap.add_argument("--plain-aiw", action="store_true",
                    help="use the sample track's AIW completely unchanged (spawns at the sample's garage spot); "
                         "for ruling out the generated AIW if rF2 crashes")
    ap.add_argument("--no-reflection-maps", action="store_true",
                    help="leave the STATIC01/REFMAP0 reflection maps out of the scene")
    ap.add_argument("--no-placeholder-aiw", action="store_true",
                    help="don't copy the sample track's AIW when the layout has none")
    args = ap.parse_args()

    gmt_dir, ref = Path(args.gmt), Path(args.reference)
    scn_path = Path(args.scn) if args.scn else next(iter(sorted(gmt_dir.glob("*.scn"))), None)
    if scn_path is None:
        sys.exit(f"no .scn in {gmt_dir}")
    tdf = next(iter(sorted(ref.glob("*.tdf"))), None)
    sky = next((p for p in (ref / "Assets" / "GMT").glob("*") if p.name.lower() == "skyboxi.gmt"), None)
    sky_tex = next((p for p in (ref / "Assets" / "Maps").glob("*") if p.name.lower() == "bka.dds"), None)
    if not (tdf and sky and sky_tex):
        sys.exit(f"sample track files not found under {ref} (need *.tdf, Assets/GMT/skyboxi.gmt, "
                 f"Assets/Maps/BKA.DDS)")

    root = Path(args.out) / args.folder
    gmt_out, maps_out, layout_out = root / "Assets" / "GMT", root / "Assets" / "Maps", root / args.layout
    for d in (gmt_out, maps_out, layout_out):
        d.mkdir(parents=True, exist_ok=True)

    gmts = sorted(gmt_dir.glob("*.gmt"))
    for g in gmts:
        shutil.copy2(g, gmt_out / g.name)
    shutil.copy2(sky, gmt_out / "SkyBoxi.gmt")
    textures = sorted(Path(args.textures).glob("*.dds"))
    for t in textures:
        shutil.copy2(t, maps_out / t.name)
    shutil.copy2(sky_tex, maps_out / sky_tex.name)
    shutil.copy2(tdf, root / f"{args.folder}.tdf")

    # Scene: sample-track header with our search paths, then the exported instances with the
    # right collision flags (patched again here in case the export wasn't), then the sky.
    up = args.folder.upper()
    search = "\n".join(f"SearchPath={p}" for p in
                       (".", up, f"{up}\\{args.layout.upper()}", f"{up}\\ASSETS\\GMT", f"{up}\\ASSETS\\MAPS"))
    exported, _ = patch(scn_path.read_text(errors="replace"))
    # 3DSimED writes "VisGroups=(32)ReflectPlane=..."; the sample track separates them with a space.
    blocks = [re.sub(r"\)(?=[A-Za-z])", ") ", b) for b in instance_blocks(exported)]
    lap = Lap(args.centreline)
    names = [re.match(r"Instance\s*=\s*(\S+)", b).group(1) for b in blocks]
    scn = (SCN_HEADER.format(search_paths=search) + "\n".join(blocks) + "\n" + SKY_INSTANCE
           + ("" if args.no_reflection_maps else reflection_mappers(names, lap)))
    write_crlf(layout_out / f"{args.layout}.scn", scn)

    summary = json.loads(Path(args.summary).read_text())
    lon, lat = Transformer.from_crs("EPSG:27700", "EPSG:4326", always_xy=True).transform(*summary["origin_bng"])
    km = summary["length_m"] / 1000
    filters = " ".join(dict.fromkeys(["rFRS", "TMOD", "NSCRS", "IndyCar", *args.filter]))
    gdb = GDB.format(filters=filters, layout=args.layout, folder=args.folder, track_name=args.track_name, venue=args.venue,
                     km=km, miles=km / 1.609344, lat=lat, lon=lon, alt=summary["origin_alt_m"])
    write_crlf(layout_out / f"{args.layout}.gdb", gdb)

    # rF2 only lists a layout that has an AIW (AI line, grid, garages) next to its .gdb and .scn. Until a
    # Teesside one is recorded, use the sample track's with its grid/pit/garage spots moved onto our start
    # straight. A generated file (marker line) or a plain copy of the sample is replaced on every run; an
    # AIW recorded in ModDev is never touched. Same for the TV cameras.
    sample_aiw = next((p for p in ref.rglob("*") if p.suffix.lower() == ".aiw"), None)
    sample_cam = next((p for p in ref.rglob("*") if p.suffix.lower() == ".cam" and p.parent != ref), None)

    def replaceable(ext, sample):
        found = [p for p in layout_out.glob("*") if p.suffix.lower() == ext]
        if not found:
            return True, None
        text = found[0].read_bytes()
        ours = MARKER.encode() in text or (sample is not None and text == sample.read_bytes())
        return ours, found[0]

    aiw_state, cam_state = "none", "none"
    ok, old = replaceable(".aiw", sample_aiw)
    if ok and not args.no_placeholder_aiw:
        if sample_aiw is None:
            sys.exit(f"no .AIW under {ref} to use as a placeholder")
        if old is not None:
            old.unlink()
        if args.plain_aiw:
            shutil.copy2(sample_aiw, layout_out / f"{args.layout}.AIW")
            aiw_state = "plain copy of the sample's (spawn at the sample's garage spot)"
        else:
            write_crlf(layout_out / f"{args.layout}.AIW",
                       relocate_aiw(sample_aiw.read_bytes().decode("latin-1"), lap))
            aiw_state = "generated"
    elif old is not None:
        aiw_state = f"kept {old.name}"
    ok, old = replaceable(".cam", sample_cam)
    if ok and sample_cam is not None:
        if old is not None:
            old.unlink()
        write_crlf(layout_out / f"{args.layout}.cam", make_cam(sample_cam.read_bytes().decode("latin-1"), lap))
        cam_state = "generated"
    elif old is not None:
        cam_state = f"kept {old.name}"

    icons = write_icons(args.centreline, layout_out, root, args.folder, args.layout, args.track_name)
    copies, removed = placeholder_copies(ref, layout_out, args.layout)
    clone = control_clone(ref, Path(args.out)) if args.control_clone else None

    missing = sorted({"xfinish", "xsector1", "xsector2", "xpitin", "xpitout"} - set(names))
    print(f"Wrote {root}")
    print(f"  {len(gmts)} meshes + sky, {len(textures)} textures + sky texture, {len(blocks)} instances in the scene")
    print(f"  track info: {args.track_name}, {km:.3f} km, lat {lat:.5f} lon {lon:.5f}")
    if aiw_state == "generated":
        print(f"  AIW: generated from {sample_aiw.name}: grid, pits and garages on Teesside's start straight "
              f"(you spawn just past the line); racing line is still the sample's, so record a Teesside one")
    else:
        print(f"  AIW: {aiw_state}")
    print(f"  TV cameras: {'12 Teesside tracking cameras' if cam_state == 'generated' else cam_state}")
    print(f"  icons/thumbnail/loading screen: {', '.join(p.name for p in icons)}")
    if copies:
        print(f"  placeholders from the sample track: {', '.join(p.name for p in copies)}")
    if removed:
        print(f"  removed the sample track's RealRoad presets (they only fit its road): "
              f"{', '.join(p.name for p in removed)}")
    if clone:
        print(f"  control track: {clone} (shows as 'ZZ Test A (sample copy)')")
    if missing:
        print(f"WARNING: the export has no {', '.join(missing)}; rF2 needs these timing/pit gates", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
